#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import ts from 'typescript';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = path.join(repositoryRoot, 'packages', 'native-epub-kit');
const entryPath = path.join(packageRoot, 'src', 'index.ts');
const outputPath = path.join(packageRoot, 'docs', 'api-reference.md');
const checkOnly = process.argv.includes('--check');

const configPath = path.join(packageRoot, 'tsconfig.json');
const configFile = ts.readConfigFile(configPath, ts.sys.readFile);
if (configFile.error) failDiagnostics([configFile.error]);

const parsedConfig = ts.parseJsonConfigFileContent(
  configFile.config,
  ts.sys,
  packageRoot,
  { noEmit: true },
  configPath
);
if (parsedConfig.errors.length > 0) failDiagnostics(parsedConfig.errors);

const program = ts.createProgram(parsedConfig.fileNames, parsedConfig.options);
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length > 0) failDiagnostics(diagnostics);

const checker = program.getTypeChecker();
const entry = program.getSourceFile(entryPath);
const moduleSymbol = entry && checker.getSymbolAtLocation(entry);
if (!entry || !moduleSymbol)
  throw new Error('Unable to resolve the public TypeScript entry point.');

const exports = checker
  .getExportsOfModule(moduleSymbol)
  .map((symbol) => describeExport(symbol))
  .sort((left, right) => left.name.localeCompare(right.name));

const groups = [
  ['Components and classes', ['component', 'class']],
  ['Functions', ['function']],
  ['Constants', ['constant']],
  ['Types and interfaces', ['type']],
];

const lines = [
  '# API reference',
  '',
  '<!-- Generated by scripts/generate-api-reference.mjs. Do not edit by hand. -->',
  '',
  `This catalog contains all ${exports.length} public exports from \`native-epub-kit\`.`,
  'It is generated from the TypeScript compiler graph, so aliases and `export *`',
  'surfaces cannot silently disappear from the documentation. The installed',
  "package's `build/index.d.ts` remains the canonical full declaration source.",
  '',
  'Regenerate with `pnpm docs:api`; verify without rewriting with',
  '`pnpm docs:api:check`.',
  '',
];

for (const [heading, kinds] of groups) {
  const entries = exports.filter((item) => kinds.includes(item.kind));
  if (entries.length === 0) continue;
  lines.push(`## ${heading}`, '');
  lines.push('| Export | Declaration | Summary | Source |');
  lines.push('| --- | --- | --- | --- |');
  for (const item of entries) {
    lines.push(
      `| \`${escapeCell(item.name)}\` | \`${escapeCell(item.signature)}\` | ${escapeCell(item.summary)} | \`${escapeCell(item.source)}\` |`
    );
  }
  lines.push('');
}

lines.push(
  '## Contract notes',
  '',
  '- Persist complete Readium Locator JSON; percentage is display state, not a',
  '  replacement position format.',
  '- Treat capability and precision fields as authoritative; platform parity is',
  '  explicit rather than inferred.',
  '- The SDK is headless. Persistence, product UI, sharing, networking, and',
  '  external navigation remain consumer responsibilities.',
  '- APIs prefixed `unstable_qualification` are excluded from this public export',
  '  catalog and are not consumer contracts.',
  ''
);

const rendered = await prettier.format(lines.join('\n').replace(/\n{3,}/g, '\n\n'), {
  parser: 'markdown',
});

if (checkOnly) {
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (existing !== rendered) {
    console.error('API reference is missing or stale. Run `pnpm docs:api`.');
    process.exit(1);
  }
  console.log(`API reference is current (${exports.length} exports).`);
} else {
  fs.writeFileSync(outputPath, rendered);
  console.log(`Wrote ${path.relative(repositoryRoot, outputPath)} (${exports.length} exports).`);
}

function describeExport(symbol) {
  const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  const declaration = chooseDeclaration(target.declarations ?? symbol.declarations ?? []);
  if (!declaration) throw new Error(`Public export ${symbol.name} has no declaration.`);

  const kind = declarationKind(symbol.name, target, declaration);
  return {
    kind,
    name: symbol.name,
    signature: declarationSignature(target, declaration, kind),
    source: sourceLocation(declaration),
    summary: documentationSummary(symbol, target),
  };
}

function chooseDeclaration(declarations) {
  return (
    declarations.find((declaration) => !declaration.getSourceFile().isDeclarationFile) ??
    declarations[0]
  );
}

function declarationKind(name, symbol, declaration) {
  if (name === 'EpubReaderView') return 'component';
  if (symbol.flags & ts.SymbolFlags.Class) return 'class';
  if (symbol.flags & (ts.SymbolFlags.Function | ts.SymbolFlags.Method)) return 'function';
  if (
    symbol.flags &
    (ts.SymbolFlags.Interface |
      ts.SymbolFlags.TypeAlias |
      ts.SymbolFlags.TypeParameter |
      ts.SymbolFlags.Enum)
  ) {
    return 'type';
  }
  if (ts.isFunctionDeclaration(declaration)) return 'function';
  return 'constant';
}

function declarationSignature(symbol, declaration, kind) {
  const formatFlags =
    ts.TypeFormatFlags.NoTruncation |
    ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope |
    ts.TypeFormatFlags.WriteArrowStyleSignature;

  if (kind === 'function') {
    const type = checker.getTypeOfSymbolAtLocation(symbol, declaration);
    const signatures = checker.getSignaturesOfType(type, ts.SignatureKind.Call);
    const rendered = signatures.map((signature) => checker.signatureToString(signature));
    return shorten(rendered.join(' | ') || `function ${symbol.name}`);
  }

  if (kind === 'type') {
    if (ts.isTypeAliasDeclaration(declaration)) {
      return shorten(
        `type ${symbol.name} = ${checker.typeToString(
          checker.getTypeFromTypeNode(declaration.type),
          declaration,
          formatFlags
        )}`
      );
    }
    if (ts.isInterfaceDeclaration(declaration)) return `interface ${symbol.name}`;
    if (ts.isEnumDeclaration(declaration)) return `enum ${symbol.name}`;
    return `type ${symbol.name}`;
  }

  if (kind === 'class') return `class ${symbol.name}`;

  const type = checker.getTypeOfSymbolAtLocation(symbol, declaration);
  return shorten(`const ${symbol.name}: ${checker.typeToString(type, declaration, formatFlags)}`);
}

function documentationSummary(alias, target) {
  const parts = alias.getDocumentationComment(checker);
  const fallback = target.getDocumentationComment(checker);
  const value = ts
    .displayPartsToString(parts.length > 0 ? parts : fallback)
    .replace(/\s+/g, ' ')
    .trim();
  if (!value) return 'Public typed contract.';
  return shorten(value.split(/(?<=[.!?])\s/)[0] ?? value, 180);
}

function sourceLocation(declaration) {
  const sourceFile = declaration.getSourceFile();
  const relative = path.relative(packageRoot, sourceFile.fileName).split(path.sep).join('/');
  const { line } = sourceFile.getLineAndCharacterOfPosition(declaration.getStart(sourceFile));
  return `${relative}:${line + 1}`;
}

function shorten(value, limit = 320) {
  const normalized = value.replace(/\s+/g, ' ').trim();
  return normalized.length <= limit ? normalized : `${normalized.slice(0, limit - 1)}…`;
}

function escapeCell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/`/g, '\\`').replace(/\n/g, ' ');
}

function failDiagnostics(diagnosticsToPrint) {
  console.error(
    ts.formatDiagnosticsWithColorAndContext(diagnosticsToPrint, {
      getCanonicalFileName: (fileName) => fileName,
      getCurrentDirectory: () => repositoryRoot,
      getNewLine: () => '\n',
    })
  );
  process.exit(1);
}
